/**
 * Regenerates `src/workstation/chrome/eastAsianWidthData.ts` from the real
 * `get-east-asian-width` package (Ink's `string-width` dependency) — the
 * data coco's own width table is ported from (OSS-2785 / coco#2164).
 *
 * Run with `npm run build:eaw` whenever `get-east-asian-width` is bumped.
 * ESM-only, so this runs under `tsx`, not the CJS build/test pipeline.
 */
import * as fs from 'fs'
import * as path from 'path'
import { eastAsianWidth } from 'get-east-asian-width'

const pkgPath = path.join('node_modules', 'get-east-asian-width', 'package.json')
const pkg: { version: string } = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))

const MAX_CODE_POINT = 0x10ffff

function isWideOrFullwidth(codePoint: number): boolean {
  // `ambiguousAsWide: false` matches `string-width`'s default
  // `ambiguousIsNarrow: true` — ambiguous-width code points measure as 1.
  return eastAsianWidth(codePoint, { ambiguousAsWide: false }) === 2
}

function buildRanges(): number[] {
  const ranges: number[] = []
  let start = -1

  for (let cp = 0; cp <= MAX_CODE_POINT; cp++) {
    const wide = isWideOrFullwidth(cp)
    if (wide && start === -1) {
      start = cp
    } else if (!wide && start !== -1) {
      ranges.push(start, cp - 1)
      start = -1
    }
  }

  if (start !== -1) {
    ranges.push(start, MAX_CODE_POINT)
  }

  return ranges
}

function main(): void {
  const ranges = buildRanges()
  const outPath = path.join('src', 'workstation', 'chrome', 'eastAsianWidthData.ts')

  const content = `// AUTO-GENERATED by bin/generateEastAsianWidth.ts — DO NOT EDIT BY HAND.
// Re-run \`npm run build:eaw\` after bumping get-east-asian-width (currently
// pinned at ${pkg.version} — see cellWidth.ts and the OSS-2785 parity test).
//
// Flat [start, end, start, end, ...] pairs of inclusive code-point ranges
// that measure as 2 cells wide (East Asian Width Wide or Fullwidth, with
// Ambiguous resolved to narrow — same default as \`string-width\`).

export const WIDE_RANGES: readonly number[] = ${JSON.stringify(ranges)}

/** Binary search \`ranges\` (a flat, sorted [start, end, ...] pair list) for \`codePoint\`. */
export function isInRange(ranges: readonly number[], codePoint: number): boolean {
  let low = 0
  let high = Math.floor(ranges.length / 2) - 1

  while (low <= high) {
    const mid = Math.floor((low + high) / 2)
    const i = mid * 2
    if (codePoint < ranges[i]) {
      high = mid - 1
    } else if (codePoint > ranges[i + 1]) {
      low = mid + 1
    } else {
      return true
    }
  }

  return false
}
`

  fs.writeFileSync(outPath, content)
  console.log(`Wrote ${ranges.length / 2} ranges to ${outPath}`)
}

main()
